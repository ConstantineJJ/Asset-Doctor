import {openJointDetails,closeJointDetails} from './rig-toolbar-probe';
import {test,expect} from '@playwright/test';
import {rigFixture} from '../rig-fixtures';
import {rigViewerState} from './rig-runtime-probe';

test('Rig editor preserves authored rest across real gizmo drag, playback, preview, retiming and history',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message)); await page.goto('/');
 await page.locator('header input[type=file]').setInputFiles({name:'rig-edit.glb',mimeType:'model/gltf-binary',buffer:Buffer.from(rigFixture().buffer)});
 await expect(page.getByRole('button',{name:'Rescan',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Rig',exact:true}).click();
 await page.getByTestId('rig-mode-edit').click();
 const initial=await rigViewerState(page);
 const root=initial.bones.find(bone=>bone.name==='Root')!;
 await page.mouse.click(...root.screen as [number,number]);
 await expect.poll(async()=>(await rigViewerState(page)).selected).toBe(root.uuid);
 await openJointDetails(page); await page.getByLabel('Joint position X',{exact:true}).fill('1.4');
 await page.getByRole('button',{name:'Apply Position',exact:true}).click(); await closeJointDetails(page);
 await expect.poll(async()=>(await rigViewerState(page)).bones.find(bone=>bone.name==='Root')!.position[0]).toBe(1.4);
 await page.getByTestId('rig-mode-pose').click();
 await openJointDetails(page); await page.getByLabel('Joint rotation Z',{exact:true}).fill('30');
 await page.getByRole('button',{name:'Preview Rotation',exact:true}).click(); await closeJointDetails(page);
 expect((await rigViewerState(page)).revision).toBe(1);
 await page.getByTestId('rig-mode-edit').click();
 expect((await rigViewerState(page)).bones.find(bone=>bone.name==='Root')!.quaternion).toEqual([0,0,0,1]);
 await page.getByTestId('rig-mode-pose').click();
 await page.getByTitle('Play',{exact:true}).click();
 await page.getByTitle('Stop & Reset',{exact:true}).click();
 expect((await rigViewerState(page)).bones.find(bone=>bone.name==='Root')!.position).toEqual([1.4,2,0]);
 await page.getByLabel('Export clip duration').fill('8');
 await page.getByRole('button',{name:'Retime Selected Clip',exact:true}).click();
 expect((await rigViewerState(page)).durations).toEqual([8,4,4,4]);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 expect((await rigViewerState(page)).durations).toEqual([4,4,4,4]);
 await page.getByTestId('rig-mode-edit').click();
 await page.waitForTimeout(100);
 const beforeDrag=await rigViewerState(page);
 const handle=beforeDrag.handles.find(handle=>handle.axis==='X')!;expect(handle).toBeTruthy();
 await page.mouse.move(...handle.screen as [number,number]);await page.mouse.down();await page.mouse.move(handle.screen[0]+30,handle.screen[1],{steps:6});await page.mouse.up();
 await expect.poll(async()=>(await rigViewerState(page)).revision).toBe(beforeDrag.revision!+1);
 expect((await rigViewerState(page)).bones.find(bone=>bone.name==='Root')!.position).not.toEqual([1.4,2,0]);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 expect((await rigViewerState(page)).bones.find(bone=>bone.name==='Root')!.position).toEqual([1.4,2,0]);
 expect(errors).toEqual([]);
});
